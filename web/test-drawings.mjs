import ts from 'typescript';import {readFileSync} from 'node:fs';import assert from 'node:assert/strict';
const js=ts.transpileModule(readFileSync(new URL('./src/drawingTools.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {fibPrices,normalizeDrawingRecords,drawingStyle,hitTestDrawing}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const levels=fibPrices({points:[{time:1,price:100},{time:2,price:200}]});
assert.equal(levels.find(x=>x.ratio===0).price,200);assert.equal(levels.find(x=>x.ratio===1).price,100);assert.equal(levels.find(x=>x.ratio===.618).price,138.2);
assert.equal(fibPrices({points:[{time:1,price:200},{time:2,price:100}]}).find(x=>x.ratio===.5).price,150);
assert.deepEqual(fibPrices({points:[{time:1,price:1},{time:1,price:2}]}),[]);
console.log('Fibonacci: ascending, descending, endpoints, retracement and invalid anchors passed');
const horizontal=normalizeDrawingRecords({'US.SNDK:5m':[100,101]},'horizontal')['US.SNDK:5m'];
assert.equal(horizontal[0].price,100);assert.equal(horizontal[0].visible,true);assert.equal(horizontal[0].lineStyle,2);
assert.deepEqual(normalizeDrawingRecords({'US.SNDK:5m':horizontal},'horizontal')['US.SNDK:5m'],horizontal);
const trend=normalizeDrawingRecords({test:[[{time:1,price:10},{time:2,price:20}]]},'trend').test;
assert.equal(trend[0].points.length,2);assert.equal(trend[0].lineWidth,2);
const fib=normalizeDrawingRecords({test:[{points:[{time:1,price:10},{time:2,price:20}],color:'#ffcc00'}]},'fib').test;
assert.equal(fib[0].color,'#ffcc00');assert.equal(fib[0].visible,true);
assert.equal(drawingStyle({color:'bad',lineWidth:999,lineStyle:99},'horizontal').lineWidth,1);
assert.equal(drawingStyle({color:'bad',lineWidth:999,lineStyle:99},'horizontal').color,'#c6d6e7');
assert.equal(hitTestDrawing({x:50,y:101},horizontal,[],[],v=>v,v=>v).id,horizontal[1].id);
assert.equal(hitTestDrawing({x:50,y:100},horizontal.map(h=>({...h,visible:false})),[],[],v=>v,v=>v),null);
assert.equal(hitTestDrawing({x:1.5,y:15},[],trend,[],v=>v,v=>v).kind,'trend');
assert.deepEqual(normalizeDrawingRecords({test:[null,{},'invalid']},'fib').test,[]);
console.log('Drawing migration, style validation and individual hit selection passed');
const coloredFib={points:[{time:1,price:10},{time:2,price:20}],color:'#ffcc00',levelColors:{'0':'#ff0000','0.618':'#00ff00','1':'bad','junk':'#000000'}};
assert.equal(fibPrices(coloredFib).find(l=>l.ratio===0).color,'#ff0000');
assert.equal(fibPrices(coloredFib).find(l=>l.ratio===.618).color,'#00ff00');
assert.equal(fibPrices(coloredFib).find(l=>l.ratio===1).color,'#ffcc00');
const normalizedColored=normalizeDrawingRecords({test:[coloredFib]},'fib').test;
assert.deepEqual(normalizedColored[0].levelColors,{'0':'#ff0000','0.618':'#00ff00'});
assert.deepEqual(normalizeDrawingRecords({test:normalizedColored},'fib').test,normalizedColored);
assert.equal(hitTestDrawing({x:50,y:109},[horizontal[0]],[],[],v=>v,v=>v).id,horizontal[0].id);
assert.equal(hitTestDrawing({x:50,y:111},[horizontal[0]],[],[],v=>v,v=>v),null);
console.log('Fibonacci level colors survive reload, invalid colors fall back, selection tolerates a 10px near miss');
const ray=normalizeDrawingRecords({test:[{id:'ray',points:[{time:20,price:20},{time:10,price:10}],extend:'right'}]},'trend').test;
assert.equal(hitTestDrawing({x:50,y:50},[],ray,[],v=>v,v=>v).id,'ray');
assert.equal(hitTestDrawing({x:-20,y:-20},[],ray,[],v=>v,v=>v),null);
assert.equal(hitTestDrawing({x:-20,y:-20},[],ray.map(v=>({...v,extend:'both'})),[],v=>v,v=>v).id,'ray');
assert.equal(normalizeDrawingRecords({test:[{...ray[0],extend:'bad'}]},'trend').test[0].extend,'none');
assert.equal(fibPrices({...coloredFib,levels:[1.272,1.618]}).find(l=>l.ratio===1.618).price,3.8200000000000003);
console.log('Trend rays honor time direction and Fibonacci extension prices passed');
