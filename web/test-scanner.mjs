import assert from 'node:assert/strict';
import {loadTS} from './test-load-ts.mjs';
const {scanBars,operand,defaultRule}=await loadTS('scanner');
const bars=values=>values.map((close,i)=>({time:i*86400,open:close,high:close+1,low:close-1,close,volume:100,session:'RTH',session_date:String(i),trade_date:String(i)}));
const rule={left:operand('PRICE'),op:'cross_above',right:{...operand('NUMBER'),value:10}};
assert.equal(scanBars(bars([9,9,11]),[rule],'all',1,true).match,true);
assert.equal(scanBars(bars([9,9,11]),[rule],'all',1,false).match,false);
assert.equal(scanBars(bars([9,11,12]),[rule],'all',1,true).match,false);
assert.equal(scanBars(bars([9,11,12]),[rule],'all',2,true).match,true);
assert.equal(scanBars(bars([9,11,12]),[rule],'all',1,false).match,true);
const state={...rule,op:'lt'};
assert.equal(scanBars(bars([9,9,11]),[rule,state],'all',1,true).match,false);
assert.equal(scanBars(bars([9,9,11]),[rule,state],'any',1,true).match,true);
const ma={left:{...operand('SMA'),params:{period:2}},op:'cross_above',right:{...operand('SMA'),params:{period:3}}};
assert.equal(scanBars(bars([5,4,3,8]),[ma],'all',1,true).match,true);
assert.throws(()=>scanBars(bars([5,4,3]),[{...ma,left:{...ma.left,params:{period:20}}}],'all',1,true),/预热/);
assert.doesNotThrow(()=>scanBars(bars(Array.from({length:100},(_,i)=>10+i+Math.sin(i))),[defaultRule()],'all',5,true));
assert.equal(scanBars(bars([1,2,4]),[{...rule,op:'reach',right:{...operand('NUMBER'),value:3}}],'all',1,true).match,true);
console.log('Scanner regression checks passed');
