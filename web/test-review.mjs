import assert from 'node:assert/strict';
import {loadTS} from './test-load-ts.mjs';
const {marketToday,shiftDay,normalizeReviewSymbol,acknowledgeReviewDraft}=await loadTS('reviewClient');
const {reviewMentions,collectReviewMentions}=await loadTS('reviewClient');
const instant=new Date('2026-11-18T01:00:00Z');
assert.equal(marketToday('CN',instant),'2026-11-18');
assert.equal(marketToday('US',instant),'2026-11-17');
assert.equal(shiftDay('2026-12-31',1),'2027-01-01');
assert.equal(shiftDay('2026-11-02',-7),'2026-10-26');
assert.equal(normalizeReviewSymbol('aapl','US'),'US.AAPL');
assert.equal(normalizeReviewSymbol('600519','CN'),'SH.600519');
assert.equal(normalizeReviewSymbol('000001','CN'),'SZ.000001');
assert.equal(normalizeReviewSymbol('SH.000001','CN'),'SH.000001');
assert.throws(()=>normalizeReviewSymbol('US.AAPL','CN'));
assert.throws(()=>normalizeReviewSymbol('SH.600519','US'));
assert.throws(()=>normalizeReviewSymbol('BRK-B','US'));
assert.throws(()=>normalizeReviewSymbol('ABCDEFGHIJKLM','US'));
const snapshot={revision:0,lesson:'submitted'};
const newerDraft={version:1,saved:false,value:{revision:0,lesson:'edited while saving'},owner:'tab-a',lineage:'draft-a'};
const kept=acknowledgeReviewDraft(JSON.stringify(newerDraft),snapshot,1,'tab-a','draft-a');
assert.equal(kept.value.lesson,'edited while saving');
assert.equal(kept.value.revision,1);
assert.equal(kept.saved,false);
const committed=acknowledgeReviewDraft(JSON.stringify({version:1,value:snapshot,owner:'tab-a',lineage:'draft-a'}),snapshot,1,'tab-a','draft-a');
assert.equal(committed.saved,true);
assert.equal(committed.value.revision,1);
const foreign=acknowledgeReviewDraft(JSON.stringify({...newerDraft,owner:'tab-b'}),snapshot,1,'tab-a','draft-a');
assert.equal(foreign.value.revision,0,'A foreign editor draft must retain its stale revision for conflict detection');
const body='[[SH.600519|贵州茅台]] 等回踩。\n[[SZ.000001]] 观察。';
assert.deepEqual(reviewMentions(body,'CN').map(m=>body.slice(m.index,m.index+m.length)),['[[SH.600519|贵州茅台]]','[[SZ.000001]]']);
assert.deepEqual(collectReviewMentions({context:body,reason:'',lesson:'[[sh.600519]] 和 [[US.AAPL]]',plan:''},'CN'),
 [{symbol:'SH.600519',name:'贵州茅台'},{symbol:'SZ.000001',name:''}]);
console.log('Review market dates, week navigation and symbol validation passed.');
