export function IndicatorGuideContent({name}:{name:string}){
 const catalog=advancedCatalog[name],source=tdxCatalog[name]?.source;
 const paragraphs=name==='FULAI'?fulai:name==='HAOYUNLAI_WAVE'?wave:[catalog?.description,reading[name]].filter((line):line is string=>Boolean(line));
 if(!paragraphs.length)return null;
 const rules=signalPrinciples[name]||[];
 const observed=observations[name];
 return <>
  {paragraphs.map(line=><p key={line}>{line}</p>)}
  {rules.length>0&&<><strong>触发点是怎样算出来的</strong>{rules.map(line=><p key={line}>{line}</p>)}</>}
  {observed&&<><strong>读图示例 · 可以怎样定义触发点</strong><p>{observed}</p><small>图上持续绘制指标值，示例条件可用于读图比较。</small></>}
  <p>核对提示时请使用同一周期和参数。上穿指上一根在对方下方或相等、本根严格高于对方；下穿反向比较。当前 K 线的收盘价随行情更新，收线后才能核对最终值。</p>
  {source&&<a href={source} target="_blank" rel="noreferrer">查看原始指标说明</a>}
 </>;
}

export default function IndicatorGuide({name}:{name:string}){
 return <details className="indicator-guide"><summary>指标教程 · 计算与读图</summary><IndicatorGuideContent name={name}/></details>;
}
